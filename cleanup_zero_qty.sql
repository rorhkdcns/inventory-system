-- 이전 버그로 인해 수량이 0인데도 삭제되지 않고 남아있는 상품 정리용 스크립트

-- =====================================================
-- 1단계: 먼저 수량 0인 상품 목록을 "확인만" 합니다 (아무것도 지우지 않음)
-- =====================================================
select id, col as "열", can as "칸", floor as "층", name as "상품명", qty as "수량"
from inventory_items
where qty = 0
order by col, can, floor;

